-- Trial/subscription/ownership changes are billing operations. They are allowed only
-- through the service role or a trusted server-side function, never from the browser.
create or replace function public.protect_workspace_billing_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- SQL Editor / migrations run as postgres or supabase_admin. PostgREST
  -- service-role requests run as service_role. Browser sessions never do.
  if current_user in ('postgres', 'supabase_admin', 'service_role')
     or current_setting('request.jwt.claim.role', true) = 'service_role' then
    return new;
  end if;

  if new.owner_id is distinct from old.owner_id
     or new.trial_start_date is distinct from old.trial_start_date
     or new.trial_ends_at is distinct from old.trial_ends_at
     or new.subscription_status is distinct from old.subscription_status
     or new.plan is distinct from old.plan
     or new.billing_customer_id is distinct from old.billing_customer_id then
    raise exception 'Trial, subscription and ownership fields are managed by Archifex.'
      using errcode = '42501';
  end if;

  return new;
end;
$$;

create trigger workspaces_protect_billing_fields
before update on public.workspaces
for each row execute function public.protect_workspace_billing_fields();

create or replace function public.log_document_activity()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.audit_logs (workspace_id, actor_id, action, entity_type, entity_id, metadata)
  values (
    coalesce(new.workspace_id, old.workspace_id),
    auth.uid(),
    lower(tg_op),
    'document',
    coalesce(new.id, old.id),
    jsonb_build_object('title', coalesce(new.title, old.title))
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

create trigger documents_audit_activity
after insert or update or delete on public.documents
for each row execute function public.log_document_activity();

-- Registration creates a profile, an isolated organization workspace and owner membership.
-- The trial starts immediately and lasts exactly 30 days.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  organization_name text;
  base_slug text;
  candidate_slug text;
  suffix integer := 0;
  new_workspace_id uuid;
begin
  organization_name := coalesce(
    nullif(trim(new.raw_user_meta_data ->> 'organization_name'), ''),
    nullif(trim(new.raw_user_meta_data ->> 'organization'), '')
  );

  if organization_name is null then
    organization_name := coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
      nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
      'مساحة عمل'
    ) || ' Workspace';
  end if;

  insert into public.profiles (id, email, full_name, locale)
  values (
    new.id,
    new.email,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), split_part(coalesce(new.email, ''), '@', 1)),
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'locale'), ''), 'ar')
  )
  on conflict (id) do update
    set email = excluded.email,
        full_name = coalesce(profiles.full_name, excluded.full_name),
        updated_at = now();

  base_slug := lower(regexp_replace(coalesce(nullif(trim(new.raw_user_meta_data ->> 'organization_slug'), ''), organization_name), '[^a-zA-Z0-9]+', '-', 'g'));
  base_slug := trim(both '-' from base_slug);
  if base_slug is null or base_slug = '' then
    base_slug := 'workspace';
  end if;

  candidate_slug := base_slug;
  while exists (select 1 from public.workspaces w where w.slug = candidate_slug) loop
    suffix := suffix + 1;
    candidate_slug := base_slug || '-' || suffix::text;
  end loop;

  insert into public.workspaces (name, slug, owner_id)
  values (organization_name, candidate_slug, new.id)
  returning id into new_workspace_id;

  insert into public.workspace_members (workspace_id, user_id, role)
  values (new_workspace_id, new.id, 'owner');

  insert into public.categories (workspace_id, name, slug, created_by)
  values (new_workspace_id, 'عام', 'general', new.id);

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();
