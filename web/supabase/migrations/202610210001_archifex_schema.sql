-- Archifex SaaS foundation: schema
-- Parent company: مَدار فَلَك | MadarFalak
-- Every tenant-owned row carries workspace_id so RLS can isolate organizations.

create type public.workspace_plan as enum ('trial', 'starter', 'professional', 'enterprise');
create type public.subscription_status as enum ('trialing', 'active', 'past_due', 'canceled');
create type public.workspace_role as enum ('owner', 'admin', 'editor', 'viewer');
create type public.document_status as enum ('processing', 'active', 'archived');

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  full_name text,
  avatar_url text,
  locale text not null default 'ar',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.workspaces (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 2 and 160),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  owner_id uuid not null references auth.users (id) on delete restrict,
  trial_start_date timestamptz not null default now(),
  trial_ends_at timestamptz not null default (now() + interval '30 days'),
  subscription_status public.subscription_status not null default 'trialing',
  plan public.workspace_plan not null default 'trial',
  billing_customer_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint workspaces_trial_window_check check (trial_ends_at > trial_start_date)
);

create table public.workspace_members (
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  role public.workspace_role not null default 'viewer',
  invited_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  primary key (workspace_id, user_id)
);

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 120),
  slug text not null check (char_length(slug) between 1 and 140),
  color text not null default '#E0A96D',
  created_by uuid default auth.uid() references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, slug)
);

-- Composite key used by documents to guarantee a category and document share a tenant.
alter table public.categories add constraint categories_id_workspace_key unique (id, workspace_id);

create table public.documents (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  category_id uuid references public.categories (id) on delete set null,
  title text not null check (char_length(title) between 1 and 240),
  description text,
  file_name text,
  storage_bucket text not null default 'archifex-documents',
  storage_path text,
  mime_type text,
  size_bytes bigint check (size_bytes is null or size_bytes >= 0),
  status public.document_status not null default 'active',
  extracted_text text,
  metadata jsonb not null default '{}'::jsonb,
  uploaded_by uuid default auth.uid() references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  archived_at timestamptz
);

create table public.archive_records (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  document_id uuid not null references public.documents (id) on delete cascade,
  reason text,
  retention_until timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  archived_by uuid default auth.uid() references auth.users (id) on delete set null,
  archived_at timestamptz not null default now()
);

create table public.audit_logs (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  actor_id uuid references auth.users (id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id uuid,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

