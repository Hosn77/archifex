-- A workspace can never be moved between tenants, and a category must belong to the
-- same workspace as its document. The function is security definer so RLS on categories
-- cannot make a valid category look absent.
create or replace function public.ensure_document_tenant_consistency()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' then
    if new.workspace_id is distinct from old.workspace_id then
      raise exception 'A document cannot be moved to another workspace.' using errcode = '42501';
    end if;
  end if;

  if new.category_id is not null
     and not exists (
       select 1
       from public.categories c
       where c.id = new.category_id
         and c.workspace_id = new.workspace_id
     ) then
    raise exception 'The selected category does not belong to this workspace.' using errcode = '23514';
  end if;

  return new;
end;
$$;

create trigger documents_tenant_consistency
before insert or update on public.documents
for each row execute function public.ensure_document_tenant_consistency();

-- Archive records must point at a document from the same workspace.
create or replace function public.ensure_archive_record_tenant_consistency()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1
    from public.documents d
    where d.id = new.document_id
      and d.workspace_id = new.workspace_id
  ) then
    raise exception 'The archived document does not belong to this workspace.' using errcode = '23514';
  end if;

  return new;
end;
$$;

create trigger archive_records_tenant_consistency
before insert or update on public.archive_records
for each row execute function public.ensure_archive_record_tenant_consistency();

