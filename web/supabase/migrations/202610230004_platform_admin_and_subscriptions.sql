-- Archifex platform administration and subscription lifecycle.
-- Run after 202610210001, 202610210002 and 202610210003.

-- Subscription periods are separate from the free trial. A null
-- subscription_ends_at means an active subscription with no fixed end.
alter table public.workspaces
  add column if not exists subscription_started_at timestamptz,
  add column if not exists subscription_ends_at timestamptz,
  add column if not exists last_renewed_at timestamptz,
  add column if not exists billing_notes text;

create index if not exists workspaces_subscription_ends_idx
  on public.workspaces (subscription_ends_at);

-- Only explicit platform administrators may use the provider console.
-- The table is managed by the service role or SQL Editor, never by clients.
create table if not exists public.platform_admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  email text,
  created_at timestamptz not null default now()
);

alter table public.platform_admins enable row level security;

drop policy if exists "platform_admins_select_self" on public.platform_admins;
create policy "platform_admins_select_self"
on public.platform_admins for select
to authenticated
using (user_id = auth.uid());

revoke all on public.platform_admins from anon;
grant select on public.platform_admins to authenticated;
grant all on public.platform_admins to service_role;

-- Provider-side audit trail for renewals, trial extensions and status changes.
create table if not exists public.platform_audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users (id) on delete set null,
  workspace_id uuid references public.workspaces (id) on delete set null,
  action text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists platform_audit_logs_workspace_created_idx
  on public.platform_audit_logs (workspace_id, created_at desc);

alter table public.platform_audit_logs enable row level security;

revoke all on public.platform_audit_logs from anon, authenticated;
grant all on public.platform_audit_logs to service_role;
grant usage, select on sequence public.platform_audit_logs_id_seq to service_role;

-- Active subscriptions now also have an end date. A null end date keeps the
-- previous "active without expiry" behaviour for manually managed accounts.
create or replace function public.workspace_can_write(target_workspace_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.workspace_members wm
    join public.workspaces w on w.id = wm.workspace_id
    where wm.workspace_id = target_workspace_id
      and wm.user_id = auth.uid()
      and wm.role in ('owner', 'admin', 'editor')
      and (
        (
          w.subscription_status = 'active'
          and (w.subscription_ends_at is null or now() <= w.subscription_ends_at)
        )
        or (
          w.subscription_status = 'trialing'
          and now() <= w.trial_ends_at
        )
      )
  );
$$;

revoke all on function public.workspace_can_write(uuid) from public, anon;
grant execute on function public.workspace_can_write(uuid) to authenticated;

-- Browser sessions must not be able to extend their own subscription.
create or replace function public.protect_workspace_billing_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if current_user in ('postgres', 'supabase_admin', 'service_role')
     or current_setting('request.jwt.claim.role', true) = 'service_role' then
    return new;
  end if;

  if new.owner_id is distinct from old.owner_id
     or new.trial_start_date is distinct from old.trial_start_date
     or new.trial_ends_at is distinct from old.trial_ends_at
     or new.subscription_status is distinct from old.subscription_status
     or new.plan is distinct from old.plan
     or new.billing_customer_id is distinct from old.billing_customer_id
     or new.subscription_started_at is distinct from old.subscription_started_at
     or new.subscription_ends_at is distinct from old.subscription_ends_at
     or new.last_renewed_at is distinct from old.last_renewed_at
     or new.billing_notes is distinct from old.billing_notes then
    raise exception 'Trial, subscription and ownership fields are managed by Archifex.'
      using errcode = '42501';
  end if;

  return new;
end;
$$;

revoke all on function public.protect_workspace_billing_fields() from public, anon, authenticated;

